function station(
  id: string,
  slug: string,
  name: string,
  city: string,
  state: string,
  address: string,
  lat: number,
  lng: number,
  description: string,
  amenities: string[],
  imageIndexes: number[],
  opts: { featured?: boolean; rating?: number; ratingCount?: number; operatorId?: string } = {},
): Station {
  const stationChargers = chargers.filter((c) => c.station_id === id)
  return {
    id,
    operator_id: opts.operatorId ?? 'op-1',
    name,
    slug,
    description,
    state,
    city,
    address,
    latitude: lat,
    longitude: lng,
    google_maps_url: `https://www.google.com/maps/dir/?api=1&destination=${lat},${lng}`,
    contact_phone: '+234 700 382 6245',
    contact_email: 'hello@evnaija.ng',
    operating_hours: 'Open 24 hours',
    amenities,
    status: 'approved',
    is_featured: opts.featured ?? false,
    rating_average: opts.rating ?? 4.8,
    rating_count: opts.ratingCount ?? 24,
    total_chargers: stationChargers.length,
    available_chargers: stationChargers.filter((c) => c.status === 'available').length,
    images: imageIndexes.map((index, order) => ({
      id: `${id}-img-${order}`,
      station_id: id,
      image_url: STATION_IMAGE_POOL[index % STATION_IMAGE_POOL.length],
      alt_text: `${name} — charging bay ${order + 1}`,
      is_cover: order === 0,
      sort_order: order,
    })),
    chargers: stationChargers,
    created_at: ago(2400),
  }
}

